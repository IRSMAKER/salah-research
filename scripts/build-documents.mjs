import { readFileSync, writeFileSync, mkdirSync, copyFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const researchDir = join(root, "..", "Understanding The Quranic Word Salah");

const read = (name) => readFileSync(join(researchDir, name), "utf8");

const research = read("Final_Research_Salah.md");

// Presentation cleanup: the detailed conclusion contained the same
// "state, not act" section twice; keep the first, remove the second.
const detailedRaw = read("Conclusion_Salah.md");
const detailed = detailedRaw
  .replace(
    /## 10\. The ṢALĀH as a State \(Not an Act\) — The Evidence[\s\S]*?(?=---\r?\n\r?\n## 11\.)/,
    "",
  )
  .replace(/## 11\. The Fire-Stand/g, "## 10. The Fire-Stand")
  .replace(/## 12\. The Three Surah-Bridges/g, "## 11. The Three Surah-Bridges")
  .replace(/## 13\. The Settled Meaning/g, "## 12. The Settled Meaning");

// Presentation cleanup: the plain-language version repeated the comparison
// table already given under "The Key Discovery".
const simpleRaw = read("Conclusion_Salah_Simple.md");
const simple = simpleRaw.replace(
  /## The Fire-Stand vs The God-Stand \(Simple Version\)[\s\S]*?(?=---\r?\n\r?\n## The Surah-Bridges)/,
  "",
);

const output = `// Generated by scripts/build-documents.mjs. Do not edit by hand.

export const researchMarkdown = ${JSON.stringify(research)};

export const conclusionDetailedMarkdown = ${JSON.stringify(detailed)};

export const conclusionSimpleMarkdown = ${JSON.stringify(simple)};
`;

writeFileSync(join(root, "src", "data", "documents.ts"), output, "utf8");

const publicResearch = join(root, "public", "research");
mkdirSync(publicResearch, { recursive: true });

writeFileSync(join(publicResearch, "Conclusion_Salah.md"), detailed, "utf8");
writeFileSync(join(publicResearch, "Conclusion_Salah_Simple.md"), simple, "utf8");

for (const name of [
  "1_Salah_Verses.md",
  "2_Study_Order.md",
  "Verification_Salah.md",
  "Final_Research_Salah.md",
]) {
  copyFileSync(join(researchDir, name), join(publicResearch, name));
}

writeFileSync(join(root, "public", "research-salah.md"), research, "utf8");

console.log("Wrote documents.ts and public research copies.");
console.log(`Detailed conclusion sections: ${(detailed.match(/^## \d+\./gm) ?? []).length}`);
